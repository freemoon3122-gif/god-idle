class Pix:
    """재질 지도. mat[(x,y)] = 재질 이름. 나중에 그린 것이 위에 덮인다"""

    def __init__(self, w, h):
        self.w, self.h = w, h
        self.mat = {}
        self.part = {}      # 같은 재질이라도 부위가 다르면 명암을 따로 (예: 팔과 몸)
        self.detail = {}    # 명암 뒤에 그대로 찍을 색
        self._pid = 0

    def _put(self, x, y, m, pid):
        if 0 <= x < self.w and 0 <= y < self.h:
            if m is None:
                self.mat.pop((x, y), None)
                self.part.pop((x, y), None)
                self.detail.pop((x, y), None)
            else:
                self.mat[(x, y)] = m
                self.part[(x, y)] = pid
                self.detail.pop((x, y), None)

    def new(self):
        self._pid += 1
        return self._pid

    # 모든 도형은 '칸의 가운데 점'이 안에 들어가면 칠한다
    def ellipse(self, cx, cy, rx, ry, m, pid=None):
        pid = pid or self.new()
        for y in range(self.h):
            for x in range(self.w):
                if ((x + .5 - cx) / rx) ** 2 + ((y + .5 - cy) / ry) ** 2 <= 1:
                    self._put(x, y, m, pid)
        return pid

    def rect(self, x, y, w, h, m, pid=None):
        pid = pid or self.new()
        for j in range(y, y + h):
            for i in range(x, x + w):
                self._put(i, j, m, pid)
        return pid

    def poly(self, pts, m, pid=None):
        pid = pid or self.new()
        n = len(pts)
        for y in range(self.h):
            for x in range(self.w):
                px, py = x + .5, y + .5
                inside = False
                for k in range(n):
                    x0, y0 = pts[k]
                    x1, y1 = pts[(k + 1) % n]
                    if (y0 > py) != (y1 > py) and px < x0 + (py - y0) * (x1 - x0) / (y1 - y0):
                        inside = not inside
                if inside:
                    self._put(x, y, m, pid)
        return pid

    def line(self, x0, y0, x1, y1, m, pid=None):
        pid = pid or self.new()
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            self._put(x0, y0, m, pid)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy
        return pid

    def rows(self, x, y, lines, key, pid=None):
        """문자열 그림으로 재질 칠하기. key = {'a': '재질'}"""
        pid = pid or self.new()
        for j, ln in enumerate(lines):
            for i, ch in enumerate(ln):
                if ch in key:
                    self._put(x + i, y + j, key[ch], pid)
        return pid

    def erase(self, x, y):
        self._put(x, y, None, 0)

    # 세부 (명암 없이 그 색 그대로)
    def dot(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.detail[(x, y)] = c
            if (x, y) not in self.mat:
                self.mat[(x, y)] = '_'
                self.part[(x, y)] = -1

    def dots(self, x, y, lines, pal):
        for j, ln in enumerate(lines):
            for i, ch in enumerate(ln):
                if ch in pal:
                    self.dot(x + i, y + j, pal[ch])

    # ── 명암 ──
    def shade(self, flip=False):
        """부위마다 왼쪽 위가 밝고 오른쪽 아래가 어둡게.
        flip=True면 그림을 나중에 좌우로 뒤집으므로 빛을 오른쪽 위에서 오게 계산한다"""
        s = Sprite(self.w, self.h)
        boxes = {}
        for (x, y), pid in self.part.items():
            b = boxes.setdefault(pid, [x, y, x, y])
            b[0], b[1] = min(b[0], x), min(b[1], y)
            b[2], b[3] = max(b[2], x), max(b[3], y)
        for (x, y), m in self.mat.items():
            if m == '_':
                continue
            pid = self.part[(x, y)]
            ramp = RAMPS[m]
            x0, y0, x1, y1 = boxes[pid]
            fx = (x - x0) / max(1, x1 - x0)
            if flip:
                fx = 1 - fx
            fy = (y - y0) / max(1, y1 - y0)
            t = fx * .45 + fy * .75  # 0(왼쪽 위) ~ 1.2(오른쪽 아래)
            same = lambda i, j: self.part.get((i, j)) == pid  # noqa: E731
            lx = 1 if flip else -1  # 빛이 오는 쪽
            lit_edge = not same(x + lx, y) or not same(x, y - 1)
            dark_edge = not same(x - lx, y) or not same(x, y + 1)
            if t < .42:
                k = 1
            elif t < .85:
                k = 2
            else:
                k = 3
            if dark_edge and t > .35:
                k = 3
            elif lit_edge and t < .5 and not dark_edge:
                k = max(0, k - 1)
            s.px(x, y, ramp[k])
        for (x, y), c in self.detail.items():
            s.px(x, y, c)
        return s


def finish(pix, flip=False):
    s = pix.shade(flip=flip)
    if flip:
        s.img = s.img.transpose(Image.FLIP_LEFT_RIGHT)
        s.p = s.img.load()
    s.outline()
    return s


